use crate::error::Errors;

mod core;
mod error;
mod infer;
mod layout;
mod lex;
mod out_of_scope;
mod parse;
mod rename;

fn main() -> std::io::Result<()> {
    let mut current_tries = 0;
    while !std::fs::exists("Cargo.toml")? {
        std::env::set_current_dir("..")?;
        current_tries += 1;
        if current_tries > 10 {
            panic!("could not find root of Rust workspace");
        }
    }

    let file = std::fs::read_to_string("examples.fl").unwrap();

    let result = compile(&file);
    if let Some((decls, defs)) = result {
        use std::io::Write;
        let mut writer = std::io::BufWriter::new(std::fs::File::create("flow/Examples.hs")?);

        writeln!(writer, "-- Autogenerated from flow typing code.")?;
        writeln!(writer)?;

        let hlint_warnings = [
            "Avoid lambda",
            "Collapse lambdas",
            "Redundant lambda",
            "Use id",
            "Use if",
            "Use lambda",
            "Use lambda-case",
            "Use list literal",
            "Use tuple-section",
        ];
        for warning in hlint_warnings {
            writeln!(writer, "{{- HLINT ignore \"{warning}\" -}}")?;
        }

        writeln!(writer)?;
        writeln!(writer, "module Examples where")?;
        writeln!(writer)?;
        writeln!(writer, "import FlowPrelude")?;
        writeln!(
            writer,
            "import Prelude.Linear (Bool (..), Char, Either (..), Int, String, consume, dup, (*), (+), (-), (/), (==))"
        )?;
        writeln!(writer)?;
        for decl in decls {
            if defs.iter().any(|def| def.name == decl.name) {
                writeln!(writer, "{} :: {}", decl.name, core::HaskellType(&decl.ty))?;
            }
        }
        writeln!(writer)?;
        for def in defs {
            writeln!(writer, "{} = {}", def.name, core::HaskellExpr(&def.expr))?;
            writeln!(writer)?;
        }
    }

    // Invoke fourmolu, if the user has it.
    std::env::set_current_dir("flow")?;
    let fourmolu_status = std::process::Command::new("fourmolu")
        .arg("--config")
        .arg("fourmolu.yaml")
        .arg("-i")
        .arg("Examples.hs")
        .status();
    match fourmolu_status {
        Ok(_) => {}
        Err(e) => {
            if let std::io::ErrorKind::NotFound = e.kind() {
                println!();
                println!("WARNING: could not find `fourmolu` on PATH.");
                println!("Generated code will not be pretty-printed.");
            } else {
                println!("could not run fourmolu: {e:#?}")
            }
        }
    }

    println!("Compilation complete.");

    Ok(())
}

fn compile<'src>(file: &'src str) -> Option<(Vec<core::Decl<'src>>, Vec<core::Def<'src>>)> {
    let mut errors = Errors::default();
    let tokens = layout::layout(&mut errors, lex::lex(file), file);
    errors.emit(file)?;

    let parsed = parse::parse(&mut errors, tokens);
    errors.emit(file)?;

    let (decls, defs) = rename::rename(&mut errors, parsed);
    errors.emit(file)?;

    let inferred = infer::infer(&mut errors, &decls, defs);
    errors.emit(file)?;

    let (decls, defs) = core::translate(&mut errors, decls, inferred);
    errors.emit(file)?;

    Some((decls, defs))
}
